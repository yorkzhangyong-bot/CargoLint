from tests.fakes import FakeReleaseService

pytestmark = pytest.mark.integration

FIX = Path(__file__).resolve().parents[1] / "fixtures" / "taric"
EXPECTED = json.loads((FIX / "expected.json").read_text(encoding="utf-8"))
BATCH = EXPECTED["batch_id"]
OBJECTS = ("GoodsNomenclature", "Measure", "MeasureType", "GeographicalArea", "DutyExpression", "Regulation")
REGISTER = ("# Data sources and provenance\n\nGenerated by `python -m rag.loader` on 2026-10-14.\n\n"
            "| Dataset | Version | Retrieved | Licence | URL |\n|---|---|---|---|---|\n"
            "| EU Combined Nomenclature 2026 | CN 2026 | 2026-10-14 | CC BY 4.0 | https://example.invalid/cn |\n\n"
            "- Firm stop-word list: synthetic demo data.\n")
NAME = "taric-2026-10-01"
ARCHIVE = "cargolint-taric-2026-10-01.zip"

try:
    find_gpg()
    HAVE_GPG = True
except GpgNotFound:
    HAVE_GPG = False
needs_gpg = pytest.mark.skipif(not HAVE_GPG, reason="gpg not found")


def name(obj: str, batch: str = BATCH, yymmdd: str = "261001") -> str:
    return f"{obj}_{batch}_{yymmdd}.xml.gz.pgp"


def listing_html(names: list[str]) -> str:
    return "<html><body><pre>" + "".join(f'<a href="{n}">{n}</a>  2026-10-01 23:00  1K\n' for n in names) + "</pre></body></html>"


def complete(kind: str, day: str) -> dict:
    return {"assets": [f"cargolint-{kind}-{day}.zip", "metadata.json"]}


def _forbidden(what: str):
    def fail(*args, **kwargs):
        raise AssertionError(f"{what} must not be called by the TARIC refresh")
    return fail


def _signature(path: Path) -> list:
    """What the repository's own TARIC paths look like: the test must leave them as they are."""
    if path.is_dir():
        return sorted((p.relative_to(path).as_posix(), p.stat().st_size) for p in path.rglob("*") if p.is_file())
    return [path.stat().st_size] if path.exists() else []


@pytest.fixture
def taric(tmp_path, monkeypatch):
    before = (_signature(TARIC_RAW_DIR), _signature(TARIC_SNAPSHOT))
    raw = tmp_path / "raw"                       # the loader's TARIC_RAW_DIR; the script makes the batch folder under it
    (tmp_path / "data").mkdir()
    paths = SimpleNamespace(raw=raw, snapshot=tmp_path / "data" / "taric.jsonl", logs=tmp_path / "logs",
                            sources=tmp_path / "data" / "SOURCES.md", listing=tmp_path / "tot.html", downloads=[],
                            source_files={name(o): FIX / "extract" / name(o) for o in OBJECTS}, service=FakeReleaseService())
    paths.sources.write_text(REGISTER, encoding="utf-8", newline="\n")
    monkeypatch.setattr(loader, "TARIC_RAW_DIR", raw)
    monkeypatch.setattr(loader, "TARIC_SNAPSHOT", paths.snapshot)
    monkeypatch.setattr(loader, "TARIC_LOG_DIR", paths.logs)
    monkeypatch.setattr(loader, "SOURCES_MD", paths.sources)
    monkeypatch.setattr(loader, "TARIC_KEY", FIX / "keys" / "fixture.asc")
    monkeypatch.setattr(loader, "TARIC_KEY_FINGERPRINT", EXPECTED["fixture_key_fingerprint"])
    monkeypatch.setattr(loader, "NOMENCLATURE_JSONL", FIX / "nomenclature.jsonl")
    for what in ("build_nomenclature", "build_rules", "build_bti", "build_indexes", "ChromaVectorSearch", "load_index_meta",
                 "get_settings"):
        monkeypatch.setattr(loader, what, _forbidden(what))   # no index is built, opened or read (spec FR-003)

    def set_listing(names: list[str]) -> None:
        paths.listing.write_text(listing_html(names), encoding="utf-8")
        monkeypatch.setattr(rt, "TOT_URL", paths.listing.as_uri())

    def copy(url: str, dest: Path, *args, **kwargs) -> Path:
        paths.downloads.append(url)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(paths.source_files[url.rsplit("/", 1)[-1]], dest)
        return dest

    paths.set_listing = set_listing
    set_listing(list(paths.source_files))
    monkeypatch.setattr(loader, "download", copy)
    yield paths
    assert (_signature(TARIC_RAW_DIR), _signature(TARIC_SNAPSHOT)) == before   # the repository's own paths untouched


def run(paths, *argv: str) -> int:
    return rt.main(list(argv), service=paths.service)


class SneakyService(FakeReleaseService):
    """Adds an EBTI release between the "nothing new" check and the listing read before the metadata is written."""

    def list(self) -> list[dict]:
        if len(self.calls_of("list")) == 1:
            self.add("ebti-2026-11-01", **complete("ebti", "2026-11-01"))
        return super().list()


@needs_gpg
class TestPublish:
    def test_a_first_run_publishes_the_release_with_its_metadata_and_marks_it_latest(self, taric, capsys):
        taric.service = SneakyService()
        assert run(taric) == 0
        out = capsys.readouterr().out
        assert f"[refresh] tot listing: batch {BATCH}, snapshot 2026-10-01, 6 files" in out
        assert "[refresh] newest TARIC release: none" in out
        assert f"[refresh] published {NAME} (2 assets), marked latest" in out
        assert f"[refresh] kept {NAME}; deleted nothing" in out
        assert any(line.startswith(f"TARIC refresh: {NAME} published in ") for line in out.splitlines())
        assert len(taric.downloads) == 6 and all(u.startswith(taric.listing.as_uri()) for u in taric.downloads)
        header = read_snapshot_header(taric.snapshot)
        assert header["snapshot_date"] == "2026-10-01" and header["batch_id"] == BATCH   # the loader's snapshot
        folder = taric.raw / "2026-10-01"
        archive = folder / ARCHIVE
        with zipfile.ZipFile(archive) as z:
            assert z.namelist() == ["data/taric.jsonl"] and z.read("data/taric.jsonl") == taric.snapshot.read_bytes()
        meta = read_metadata(folder / "metadata.json")
        assert (meta["kind"], meta["release"], meta["snapshot_date"]) == ("taric", NAME, "2026-10-01")
        assert meta["source_version"] == f"batch {BATCH}, extract 2026-10-01"
        assert meta["source"] == "https://distr.tullverket.se/tulltaxan/" and meta["entries"] == ["data/taric.jsonl"]
        assert (meta["sha256"], meta["size"]) == (hashlib.sha256(archive.read_bytes()).hexdigest(), archive.stat().st_size)
        assert meta["current"] == {"ebti": ["ebti-2026-11-01"], "taric": [NAME]}   # from the listing re-read before writing
        service = taric.service
        calls = [c[0] for c in service.calls]
        assert calls[:2] == ["check", "list"]                                        # the "nothing new" check
        assert calls[calls.index("create") - 1] == "list"                            # re-read right before the create
        assert calls[calls.index("create") + 1] == "mark_latest" and calls[-1] == "list"   # then the prune's listing
        assert service.latest_name == NAME and service.releases[NAME]["assets"] == [ARCHIVE, "metadata.json"]
        assert "upload" not in calls

    @pytest.mark.parametrize("existing", [NAME, "taric-2026-11-02"])
    def test_nothing_new_when_a_complete_release_of_the_date_or_newer_exists(self, taric, capsys, existing):
        taric.service = FakeReleaseService({"taric-2026-08-01": complete("taric", "2026-08-01"),
                                            "taric-2026-09-01": complete("taric", "2026-09-01"),
                                            existing: complete("taric", existing[6:])}, latest="taric-2026-08-01")
        assert run(taric) == 0
        out = capsys.readouterr().out
        assert f"TARIC refresh: {existing} is already published and complete; nothing new. Use --force to rebuild and replace it." in out
        assert taric.downloads == [] and not taric.snapshot.exists()
        assert [c[0] for c in taric.service.calls] == ["check", "list", "delete", "latest", "mark_latest"]
        assert sorted(taric.service.names) == sorted(["taric-2026-09-01", existing])     # retention applied
        assert taric.service.latest_name == existing                                     # re-marked: the latest was older

    def test_nothing_new_does_not_re_mark_a_release_that_is_latest_already(self, taric):
        taric.service = FakeReleaseService({NAME: complete("taric", "2026-10-01")}, latest=NAME)
        assert run(taric) == 0
        assert [c[0] for c in taric.service.calls] == ["check", "list", "latest"]

    def test_a_nothing_new_run_whose_prune_fails_exits_3(self, taric, capsys):
        taric.service = FakeReleaseService({"taric-2026-08-01": complete("taric", "2026-08-01"),
                                            "taric-2026-09-01": complete("taric", "2026-09-01"),
                                            NAME: complete("taric", "2026-10-01")})
        taric.service.fail_at("delete", "gh: HTTP 502 (simulated)")
        assert run(taric) == 3
        err = capsys.readouterr().err
        assert err.startswith("TARIC refresh failed: the release service failed at the prune of taric-2026-08-01: gh: HTTP 502")

    def test_force_downloads_rebuilds_deletes_and_recreates(self, taric, capsys):
        taric.service = FakeReleaseService({NAME: complete("taric", "2026-10-01")}, latest=NAME)
        assert run(taric, "--force") == 0
        calls = [c[0] for c in taric.service.calls]
        assert len(taric.downloads) == 6 and taric.snapshot.exists()
        assert calls.index("delete") < calls.index("create") < calls.index("mark_latest") and "upload" not in calls
        assert taric.service.calls_of("delete") == [("delete", NAME)]
        assert taric.service.latest_name == NAME and taric.service.releases[NAME]["files"]["metadata.json"].exists()

    @pytest.mark.parametrize("remnant", [{"assets": [ARCHIVE], "draft": True}, {"assets": [ARCHIVE]}, {"assets": ["metadata.json"]}])
    def test_an_incomplete_release_of_the_date_is_deleted_and_published_afresh(self, taric, remnant):
        taric.service = FakeReleaseService({NAME: remnant})
        assert run(taric) == 0
        calls = [c[0] for c in taric.service.calls]
        assert calls.index("delete") < calls.index("create") and taric.service.calls_of("delete") == [("delete", NAME)]
        release = taric.service.releases[NAME]
        assert release["draft"] is False and release["assets"] == [ARCHIVE, "metadata.json"]

    def test_a_failing_create_is_exit_3_naming_the_step_and_the_remnant_deleted(self, taric, capsys):
        taric.service = FakeReleaseService({NAME: {"assets": [ARCHIVE], "draft": True},
                                            "taric-2026-08-01": complete("taric", "2026-08-01"),
                                            "taric-2026-07-01": complete("taric", "2026-07-01"),
                                            "taric-2026-06-01": complete("taric", "2026-06-01")})
        taric.service.fail_at("create", "gh: HTTP 500 (simulated)")
        assert run(taric) == 3
        err = capsys.readouterr().err
        assert err.startswith(f"TARIC refresh failed: the release service failed at the create of {NAME}: gh: HTTP 500")
        assert err.rstrip().endswith(f"before that it deleted the incomplete {NAME}")
        assert taric.service.calls_of("delete") == [("delete", NAME)]          # nothing else deleted: no prune ran
        assert [c[0] for c in taric.service.calls][-1] == "create"

    def test_retention_after_publishing(self, taric):
        taric.service = FakeReleaseService({"taric-2026-09-01": complete("taric", "2026-09-01"),
                                            "taric-2026-08-01": complete("taric", "2026-08-01"),
                                            "taric-2026-09-15": {"assets": ["cargolint-taric-2026-09-15.zip"]},
                                            "ebti-2026-10-14": complete("ebti", "2026-10-14"),
                                            "demo-store-v1": {"assets": ["cargolint-demo-store-v1.zip"]}})
        assert run(taric) == 0
        assert sorted(taric.service.names) == ["demo-store-v1", "ebti-2026-10-14", "taric-2026-09-01", NAME]
        meta = read_metadata(taric.service.releases[NAME]["files"]["metadata.json"])
        assert meta["current"] == {"ebti": ["ebti-2026-10-14"], "taric": [NAME, "taric-2026-09-01"]}

    def test_no_publish_builds_the_archive_and_metadata_without_touching_the_service(self, taric, capsys):
        assert run(taric, "--no-publish") == 0
        folder = taric.raw / "2026-10-01"
        assert (folder / ARCHIVE).exists() and taric.service.calls == []
        assert read_metadata(folder / "metadata.json")["current"] == {"ebti": [], "taric": [NAME]}
        assert f"TARIC refresh: {NAME} built in" in capsys.readouterr().out


@needs_gpg
class TestRefusals:
    def test_a_refused_batch_exits_1_and_publishes_nothing(self, taric, capsys):
        tampered = name("MeasureType")
        taric.source_files[tampered] = FIX / "bad" / "tampered" / tampered
        assert run(taric) == 1
        assert "TARIC load refused" in capsys.readouterr().err
        assert taric.service.names == [] and not taric.snapshot.exists()
        assert [c[0] for c in taric.service.calls] == ["check", "list"]

    def test_an_unreadable_listing_exits_1_before_any_download(self, taric, capsys, monkeypatch):
        monkeypatch.setattr(rt, "TOT_URL", (taric.listing.parent / "missing.html").as_uri())
        assert run(taric) == 1
        assert capsys.readouterr().err.startswith("TARIC refresh refused: the tot listing")
        assert taric.downloads == [] and taric.service.names == []

    def test_a_listing_with_no_complete_batch_exits_1(self, taric, capsys):
        taric.set_listing([name(o) for o in OBJECTS[:-1]])
        assert run(taric) == 1
        assert "no batch in the tot listing has all 6 object files" in capsys.readouterr().err
        assert taric.downloads == []

    def test_a_missing_or_signed_out_service_exits_2_before_any_download(self, taric, capsys):
        taric.service.fail_at("check", "gh not found: set CARGOLINT_GH or put the GitHub CLI on PATH")
        assert run(taric) == 2
        assert capsys.readouterr().err.startswith("TARIC refresh not started: the release service is not available")
        assert taric.downloads == [] and taric.service.calls == [("check",)]

    def test_a_missing_key_copy_exits_2_before_any_download(self, taric, capsys, monkeypatch):
        monkeypatch.setattr(loader, "TARIC_KEY", FIX / "keys" / "absent.asc")
        assert run(taric) == 2
        assert "key copy" in capsys.readouterr().err and taric.downloads == [] and taric.service.calls == []

    def test_bad_options_exit_2(self, taric):
        assert run(taric, "--bogus") == 2 and taric.service.calls == []
