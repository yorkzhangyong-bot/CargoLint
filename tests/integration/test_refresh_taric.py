"""Feature 013, User Story 1: the TARIC refresh end to end on the signed fixture batch with a fake release service
(contracts/refresh-cli.md; spec FR-001 to FR-005, FR-010 to FR-012). The loader's TARIC paths and key are monkeypatched
into a temporary folder as tests/integration/test_taric_loader.py does, the tot listing is a file: URL naming the six
fixture files, the download copies them from the fixtures, and the index builders are forbidden. Loads need gpg and
skip without it."""
